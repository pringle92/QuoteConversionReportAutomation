            {
                var cell = worksheet.Cells[r, checkColumn].Value;
                if (cell != null && !string.IsNullOrWhiteSpace(cell.ToString()))
                {
                    return Math.Max(r + 1, firstDataRowAfterHeaders);
                }
            }
            return firstDataRowAfterHeaders;
        }

