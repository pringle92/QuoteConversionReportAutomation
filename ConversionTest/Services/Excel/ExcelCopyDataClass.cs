        /// <summary>
        /// Asynchronously renames or moves a file, with built-in retry logic to handle transient file locks.
        /// </summary>
        /// <param name="sourcePath">The full path to the source file.</param>
        /// <param name="destinationPath">The full path to the destination file.</param>
        /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
        private async Task RenameFileWithRetryAsync(
            string sourcePath,
            string destinationPath,
            CancellationToken cancellationToken)
        {
            // Get retry parameters from configuration.
            int maxRetries = _configuration.GetValue<int>("OperationalParameters:GeneralFileOperationMaxRetries", 5);
            int initialDelayMs = _configuration.GetValue<int>("OperationalParameters:GeneralFileOperationDelayMs", 500);
            int currentDelayMs = initialDelayMs;

            // Loop for the specified number of retries.
            for (int i = 0; i < maxRetries; i++)
            {
                try
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    // Perform the file move operation on a background thread.
                    await Task.Run(() =>
                    {
                        if (File.Exists(destinationPath))
                        {
                            File.Delete(destinationPath);
                        }
                        File.Move(sourcePath, destinationPath);
                    }, cancellationToken);
                    return; // Success, exit the method.
                }
                catch (IOException ex) when (i < maxRetries - 1)
                {
                    // If an IO error occurs and it is not the last attempt, wait and retry.
                    Logger.LogWarning($"Attempt {i + 1}/{maxRetries} failed to move file: {ex.Message}. Retrying in {currentDelayMs}ms...");
                    _statusManager.Post($"Waiting for file access (Attempt {i + 1})...", MessageType.InProgress);
                    await Task.Delay(currentDelayMs, cancellationToken);
                    currentDelayMs *= 2; // Exponential backoff.
                }
                catch (OperationCanceledException)
                {
                    // Re-throw cancellation exceptions immediately.
                    throw;
                }
            }
            // If the loop completes, all retries have failed.
            throw new IOException($"Failed to move file '{sourcePath}' to '{destinationPath}' after {maxRetries} attempts.");
        }

