        /// <summary>
        /// Filters rows in the specified worksheet based on a numeric threshold in a given column.
        /// Rows where the value is less than the threshold, or cannot be parsed as a decimal, are deleted.
        /// </summary>
        /// <param name="worksheet">The Excel worksheet to filter.</param>
        /// <param name="priceColumnIndex">The 1-based index of the column containing numeric values to check.</param>
        /// <param name="threshold">The decimal threshold. Rows with values less than this will be removed.</param>
        /// <param name="cancellationToken">Cancellation token.</param>
        private async Task FilterDataSheetAsync(ExcelWorksheet worksheet, int priceColumnIndex, decimal threshold, CancellationToken cancellationToken)
        {
            if (worksheet.Dimension == null || worksheet.Dimension.Rows < 2) return;

            await Task.Run(() =>
            {
                int initialRowCount = worksheet.Dimension.Rows;
                for (int r = initialRowCount; r >= 2; r--)
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    var cellValue = worksheet.Cells[r, priceColumnIndex].Value;
                    bool deleteRow = true;

                    if (cellValue != null)
                    {
                        string valStr = cellValue.ToString()!.Replace("£", "").Replace(",", "").Trim();
                        if (decimal.TryParse(valStr, NumberStyles.Any, CultureInfo.InvariantCulture, out decimal amount))
                        {
                            if (amount >= threshold)
                            {
                                deleteRow = false;
                            }
                        }
                    }

                    if (deleteRow)
                    {
                        worksheet.DeleteRow(r, 1);
                    }
                }
            }, cancellationToken);
        }
