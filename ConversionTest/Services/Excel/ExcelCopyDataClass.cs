        /// <summary>
        /// Asynchronously processes a raw Excel report. This is the main public entry point for this class.
        /// It orchestrates copying data from a source file to a template, performing filtering,
        /// running calculations, and saving the final processed report.
        /// </summary>
        /// <param name="selectedFinYear">The financial year string (e.g., "2023_24") relevant for the report.</param>
        /// <param name="reportType">The type of report being processed, which dictates specific logic.</param>
        /// <param name="sourceFilePath">The full path to the raw source Excel file generated by Crystal Reports.</param>
        /// <param name="sourceSheetNameConfigKey">The configuration key for the name of the sheet in the source file.</param>
        /// <param name="baseFileSaveLocation">The base directory where the final processed report will be saved.</param>
        /// <param name="templateFilePath">The full path to the Excel template file that will be used.</param>
        /// <param name="destinationDataSheetNameConfigKey">The configuration key for the name of the sheet in the template where data is copied.</param>
        /// <param name="startRow">The starting row (1-based) in the source sheet from which to begin copying data.</param>
        /// <param name="startCol">The starting column (1-based) in the source sheet from which to begin copying data.</param>
        /// <param name="reportDate">The primary date for the report, used for filename generation and internal logic.</param>
        /// <param name="manualParams">Optional parameters for a manually triggered report, for additional context.</param>
        /// <param name="autoRunDef">Optional definition for an automatically triggered report.</param>
        /// <param name="cancellationToken">A token to monitor for cancellation requests from the user.</param>
        /// <returns>
        /// A task that represents the asynchronous operation. The task result is the full path to the
        /// final processed Excel file, or null if the processing fails or is cancelled.
        /// </returns>
        public async Task<string?> ProcessExcelReportAsync(
            string selectedFinYear,
            ReportType reportType,
            string sourceFilePath,
            string sourceSheetNameConfigKey,
            string baseFileSaveLocation,
            string templateFilePath,
            string destinationDataSheetNameConfigKey,
            int startRow = 1,
            int startCol = 1,
            DateTime reportDate = default,
            ManualReportParameters? manualParams = null,
            AutoReportDefinition? autoRunDef = null,
            CancellationToken cancellationToken = default)
        {
            // Start a stopwatch to measure the duration of the entire operation.
            var stopwatch = Stopwatch.StartNew();
            Logger.LogTrace($"Entering ProcessExcelReportAsync. ReportType: {reportType}, Source: {sourceFilePath}");

            // Validate that all required string parameters are not null or empty.
            ArgumentException.ThrowIfNullOrEmpty(sourceFilePath, nameof(sourceFilePath));
            ArgumentException.ThrowIfNullOrEmpty(sourceSheetNameConfigKey, nameof(sourceSheetNameConfigKey));
            ArgumentException.ThrowIfNullOrEmpty(baseFileSaveLocation, nameof(baseFileSaveLocation));
            ArgumentException.ThrowIfNullOrEmpty(templateFilePath, nameof(templateFilePath));
            ArgumentException.ThrowIfNullOrEmpty(destinationDataSheetNameConfigKey, nameof(destinationDataSheetNameConfigKey));

            // Retrieve sheet names from the application configuration.
            string sourceSheetName = _configuration.GetValue<string>($"OperationalParameters:ExcelSheetNames:{sourceSheetNameConfigKey}", "Sheet1")!;
            string destinationDataSheetName = _configuration.GetValue<string>($"OperationalParameters:ExcelSheetNames:{destinationDataSheetNameConfigKey}", "DATA")!;
            string analysisSheetName = _configuration.GetValue<string>("OperationalParameters:ExcelSheetNames:TemplateAnalysisSheet", "Analysis")!;

            // Ensure the financial year is provided for report types that require it.
            if (reportType is ReportType.Weekly or ReportType.Daily or ReportType.Daily5Day1k)
            {
                ArgumentException.ThrowIfNullOrEmpty(selectedFinYear, nameof(selectedFinYear));
            }

            // Default the report date to today if not specified for a non-custom report.
            if (reportDate == default && reportType != ReportType.Custom)
            {
                reportDate = DateTime.Today;
                Logger.LogWarning($"reportDate not specified for non-custom report. Defaulting to Today for filename: {reportDate:yyyy-MM-dd}");
            }

            // Declare variables for file paths to be used within the try block.
            string? finalFilePath = null;
            string? tempFilePath = null;

            try
            {
                // Post an initial status message to the UI.
                _statusManager.Post("Starting Excel processing...", MessageType.InProgress);
                cancellationToken.ThrowIfCancellationRequested();

                // 1. Determine and create the report-specific output folder.
                DateTime folderTimestampDate = reportType == ReportType.Custom ? DateTime.Now : reportDate;
                string? fullOutputFolderPath = FolderCreation.CreateReportSpecificFolder(reportType, baseFileSaveLocation, folderTimestampDate, _configuration);
                if (string.IsNullOrEmpty(fullOutputFolderPath))
                {
                    throw new InvalidOperationException("Failed to create or determine the report output folder.");
                }
                _statusManager.Post("Output folder prepared.", MessageType.InProgress);
                cancellationToken.ThrowIfCancellationRequested();

                // 2. Define a path for a temporary working copy of the template file. Using a GUID ensures uniqueness.
                tempFilePath = Path.Combine(fullOutputFolderPath, $"temp_processing_{Guid.NewGuid()}.xlsx");
                Logger.LogDebug($"Using temporary file: {tempFilePath}");

                // 3. Copy the template to the temporary location to avoid modifying the original template.
                if (!File.Exists(templateFilePath))
                {
                    throw new FileNotFoundException($"Excel template file not found: {templateFilePath}", templateFilePath);
                }
                await Task.Run(() => File.Copy(templateFilePath, tempFilePath, true), cancellationToken);
                _statusManager.Post("Template copied.", MessageType.InProgress);
                cancellationToken.ThrowIfCancellationRequested();

                // 4. Open the source and destination Excel packages and perform the main processing.
                _statusManager.Post("Opening Excel files for processing...", MessageType.InProgress);
                if (!File.Exists(sourceFilePath))
                {
                    throw new FileNotFoundException($"Raw source data file not found: {sourceFilePath}", sourceFilePath);
                }

                // The 'using' statements ensure that the Excel packages are properly disposed of.
                using (var sourcePackage = new ExcelPackage(new FileInfo(sourceFilePath)))
                using (var destinationPackage = new ExcelPackage(new FileInfo(tempFilePath)))
                {
                    // Get the source worksheet from the raw data file.
                    ExcelWorksheet? sourceWorksheet = sourcePackage.Workbook.Worksheets[sourceSheetName];
                    if (sourceWorksheet == null)
                    {
                        throw new FileNotFoundException($"Source sheet '{sourceSheetName}' not found in source file '{sourceFilePath}'.");
                    }

                    // Get or create the destination 'DATA' sheet in our temporary template copy.
                    ExcelWorksheet destinationDataWorksheet = GetOrCreateDestinationWorksheet(destinationPackage, destinationDataSheetName, sourceWorksheet);

                    // Map column headers to indices for robust processing. This is a key part of the refactoring.
                    var dataColumnMap = MapColumnIndices(destinationDataWorksheet, 1, new[] { "Customer", "Price", "Posting Code" });
                    ExcelWorksheet analysisSheet = destinationPackage.Workbook.Worksheets[analysisSheetName] ?? throw new InvalidOperationException($"Analysis sheet '{analysisSheetName}' not found.");
                    var analysisColumnMap = MapColumnIndices(analysisSheet, 5, new[] { "Customer", "Number of Estimates", "SOURCE FILE", "CONVERTED DATE", "FY" });

                    // Get the dimensions of the source data.
                    int sourceRowCount = sourceWorksheet.Dimension?.Rows ?? 0;
                    int sourceColCount = sourceWorksheet.Dimension?.Columns ?? 0;

                    // Copy the raw data from the source file to the 'DATA' sheet in the template.
                    _statusManager.Post("Copying data from source to template...", MessageType.InProgress);
                    if (sourceRowCount >= startRow && sourceColCount >= startCol)
                    {
                        // Determine the actual start row for data, assuming row 1 is a header.
                        int sourceDataActualStartRow = (startRow == 1 && sourceRowCount > 1) ? 2 : startRow;

                        if (sourceRowCount >= sourceDataActualStartRow)
                        {
                            ExcelRange sourceRangeToCopy = sourceWorksheet.Cells[sourceDataActualStartRow, startCol, sourceRowCount, sourceColCount];
                            ExcelRange destStartCellForData = destinationDataWorksheet.Cells[2, 1];
                            sourceRangeToCopy.Copy(destStartCellForData);
                            Logger.LogInfo($"Data copied from '{sourceSheetName}' to '{destinationDataSheetName}'.");
                        }
                    }
                    _statusManager.Post("Initial data copy to 'DATA' sheet complete.", MessageType.InProgress);
                    cancellationToken.ThrowIfCancellationRequested();

                    // Apply specific filtering for the 'Daily (5days >= £1000)' report type.
                    if (reportType == ReportType.Daily5Day1k)
                    {
                        decimal filterThreshold = _configuration.GetValue<decimal>("OperationalParameters:Daily5Day1kFilteringThreshold", 1000m);
                        _statusManager.Post($"Filtering for values >= £{filterThreshold:N0}...", MessageType.InProgress);
                        await FilterDataSheetAsync(destinationDataWorksheet, dataColumnMap["Price"], filterThreshold, cancellationToken);
                    }

                    // ADDED: New filtering logic for the NewCustomer report type.
                    else if (reportType == ReportType.NewCustomer)
                    {
                        _statusManager.Post("Filtering for New Customers by Posting Code...", MessageType.InProgress);
                        var postingCodes = _configuration.GetSection(AppConfigKeys.OperationalParameters.NewCustomerPostingCodes).Get<List<string>>();
                        if (postingCodes == null || !postingCodes.Any())
                        {
                            throw new InvalidOperationException("New Customer posting codes are not configured in appsettings.json.");
                        }
                        await FilterDataSheetByPostingCodeAsync(destinationDataWorksheet, dataColumnMap["Posting Code"], new HashSet<string>(postingCodes, StringComparer.OrdinalIgnoreCase), cancellationToken);
                        destinationDataWorksheet = destinationPackage.Workbook.Worksheets[destinationDataSheetName];
                    }
                    _statusManager.Post("Data preparation in 'DATA' sheet complete.", MessageType.InProgress);

                    // Perform all post-copy operations like populating the 'Analysis' sheet.
                    await ProcessPostCopyOperationsAsync(destinationPackage, destinationDataWorksheet, analysisSheet, dataColumnMap, analysisColumnMap, reportType, selectedFinYear, sourceFilePath, reportDate, cancellationToken);

                    // If requested, create the 'Lead Time Analysis' sheet.
                    bool shouldIncludeLeadTimeSheet = (manualParams?.IncludeLeadTimeAnalysis ?? autoRunDef?.IncludeLeadTimeAnalysis) ?? false;
                    if (shouldIncludeLeadTimeSheet)
                    {
                        cancellationToken.ThrowIfCancellationRequested();
                        await CreateLeadTimeAnalysisSheetAsync(destinationPackage, destinationDataSheetName, cancellationToken);
                    }

                    // Save all changes to the temporary Excel file.
                    _statusManager.Post("Saving processed file...", MessageType.InProgress);
                    await destinationPackage.SaveAsync(cancellationToken);
                }

                // Finalise the file by renaming the temporary file to its final name.
                _statusManager.Post("Finalising file...", MessageType.InProgress);
                string generatedFileName = await Task.Run(() => GenerateFinalFileName(reportType, reportDate, DateTime.Now), cancellationToken);
                finalFilePath = Path.Combine(fullOutputFolderPath, generatedFileName);
                await RenameFileWithRetryAsync(tempFilePath, finalFilePath, cancellationToken);
                tempFilePath = null; // Mark temp file as handled to prevent deletion in the finally block.

                // Report completion.
                _statusManager.Post("Excel processing complete.", MessageType.Success);
                stopwatch.Stop();
                Logger.LogInfo($"Excel processing finished. Final file: {finalFilePath}. Duration: {stopwatch.ElapsedMilliseconds}ms.");
                return finalFilePath;
            }
            catch (OperationCanceledException)
            {
                // Handle cancellation gracefully.
                stopwatch.Stop();
                Logger.LogWarning($"Excel processing was cancelled. Duration: {stopwatch.ElapsedMilliseconds}ms.");
                _statusManager.Post("Operation cancelled.", MessageType.Warning);
                return null;
            }
            catch (Exception ex)
            {
                // Handle any other exceptions, log them, and report the error to the user.
                stopwatch.Stop();
                Logger.LogError($"Unexpected error during Excel processing: {ex.Message}. Duration: {stopwatch.ElapsedMilliseconds}ms.", ex);
                _statusManager.Post($"Error: {ex.Message.Split('\n').FirstOrDefault()}", MessageType.Error);
                return null;
            }
            finally
            {
                // Ensure the temporary file is cleaned up if an error occurred before it was renamed.
                if (tempFilePath != null && File.Exists(tempFilePath))
                {
                    try
                    {
                        File.Delete(tempFilePath);
                        Logger.LogInfo($"Deleted lingering temporary file: {tempFilePath}");
                    }
                    catch (Exception cleanupEx)
                    {
                        Logger.LogWarning($"Failed to delete temporary file '{tempFilePath}' during cleanup: {cleanupEx.Message}");
                    }
                }
            }
        }

        /// <summary>
        /// Gets the current financial year string (e.g., "2023_24" or "FY 23/24").
        /// Uses configured financial year start month and day.
        /// </summary>
        /// <param name="useUnderscoreFormat">If true, returns format "YYYY_YY" (e.g., "2023_24"). Otherwise, "FY YY/YY" (e.g., "FY 23/24").</param>
        /// <returns>The formatted financial year string.</returns>
        public string GetCurrentFinancialYear(bool useUnderscoreFormat = false)
        {
            Logger.LogTrace($"Entering GetCurrentFinancialYear(useUnderscoreFormat: {useUnderscoreFormat})");
            DateTime today = DateTime.Today;
            // Read financial year start month/day from configuration.
            int finYearStartMonth = _configuration.GetValue<int>("OperationalParameters:FinancialYearStartMonth", 5); // Default May
            int finYearStartDay = _configuration.GetValue<int>("OperationalParameters:FinancialYearStartDay", 1);   // Default 1st

            // Determine the calendar year in which the current financial year started.
            int startYear = (today.Month > finYearStartMonth || (today.Month == finYearStartMonth && today.Day >= finYearStartDay))
                            ? today.Year
                            : today.Year - 1;
            int endYear = startYear + 1;

            string result = useUnderscoreFormat
                ? $"{startYear}_{endYear.ToString()[2..]}" // Format: 2023_24
                : $"FY {startYear.ToString()[2..]}/{endYear.ToString()[2..]}"; // Format: FY 23/24

            Logger.LogTrace($"Exiting GetCurrentFinancialYear. Result: {result}");
            return result;
        }

        /// <summary>
        /// Gets the previous financial year string from a given current financial year string (underscore format).
        /// </summary>
        /// <param name="currentFinancialYearUnderscore">The current financial year in "YYYY_YY" format (e.g., "2023_24").</param>
        /// <returns>The previous financial year in "YYYY_YY" format, or null if input is invalid.</returns>
        public string? GetPreviousFinancialYear(string currentFinancialYearUnderscore)
        {
            if (string.IsNullOrEmpty(currentFinancialYearUnderscore))
            {
                return null;
            }
            string[] parts = currentFinancialYearUnderscore.Split('_');
            if (parts.Length == 2 && int.TryParse(parts[0], out int startYear))
            {
                int prevStartYear = startYear - 1;
                return $"{prevStartYear}_{startYear.ToString()[2..]}";
            }
            return null;
        }

        /// <summary>
        /// Validates if a given date range falls entirely within a specified financial year (underscore format).
        /// </summary>
        /// <param name="selectedFinYearUnderscore">The financial year to validate against, in "YYYY_YY" format (e.g., "2023_24").</param>
        /// <param name="fromDate">The start date of the range to check.</param>
        /// <param name="toDate">The end date of the range to check.</param>
        /// <returns>True if the date range is valid for the financial year; otherwise, false.</returns>
        public bool IsFinancialYearValid(string selectedFinYearUnderscore, DateTime fromDate, DateTime toDate)
        {
            if (string.IsNullOrEmpty(selectedFinYearUnderscore))
            {
                return false;
            }
            string[] parts = selectedFinYearUnderscore.Split('_');
            if (parts.Length == 2 && int.TryParse(parts[0], out int startYear))
            {
                int finYearStartMonth = _configuration.GetValue<int>("OperationalParameters:FinancialYearStartMonth", 5);
                int finYearStartDay = _configuration.GetValue<int>("OperationalParameters:FinancialYearStartDay", 1);

                DateTime fyStartDate = new DateTime(startYear, finYearStartMonth, finYearStartDay);
                DateTime fyEndDate = fyStartDate.AddYears(1).AddDays(-1);

                return fromDate >= fyStartDate && toDate <= fyEndDate;
            }
            return false;
        }

        /// <summary>
        /// Gets the expected full file path for a final processed report.
        /// Used for checking if a report for the period already exists.
        /// </summary>
        /// <param name="reportType">The type of the report.</param>
        /// <param name="baseFileSaveLocation">The base directory where final reports are saved.</param>
        /// <param name="reportDate">The primary date for the report (e.g., end date).</param>
        /// <returns>The expected full file path, or null if an error occurs.</returns>
        public string? GetExpectedFinalFilePath(ReportType reportType, string baseFileSaveLocation, DateTime reportDate)
        {
            try
            {
                if (reportDate == default && reportType != ReportType.Custom)
                {
                    reportDate = DateTime.Today;
                }

                DateTime folderTimestampDate = reportType == ReportType.Custom ? DateTime.Now : reportDate;
                string? folderPath = FolderCreation.GetReportSpecificFolderPath(reportType, baseFileSaveLocation, folderTimestampDate, _configuration);
                if (!string.IsNullOrEmpty(folderPath))
                {
                    string fileName = GenerateFinalFileName(reportType, reportDate, DateTime.Now);
                    return Path.Combine(folderPath, fileName);
                }
            }
            catch (Exception ex)
            {
                Logger.LogError($"Error in GetExpectedFinalFilePath: {ex.Message}", ex);
            }
            return null;
        }

