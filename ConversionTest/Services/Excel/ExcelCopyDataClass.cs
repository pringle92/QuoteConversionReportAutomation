        /// <summary>
        /// Orchestrates the sequence of operations that occur after the initial raw data has been copied
        /// to the template's 'DATA' sheet. This includes populating the 'Analysis' sheet, running calculations,
        /// cleaning up unused rows, and appending data to the central Power BI file if required.
        /// </summary>
        private async Task ProcessPostCopyOperationsAsync(
            ExcelPackage package,
            ExcelWorksheet sourceDataWorksheet,
            ExcelWorksheet targetAnalysisWorksheet,
            Dictionary<string, int> dataColumnMap,
            Dictionary<string, int> analysisColumnMap,
            ReportType reportType,
            string selectedFinYear,
            string originalSourceFilePath,
            DateTime reportDate,
            CancellationToken cancellationToken)
        {
            // Log the start of the post-copy process.
            Logger.LogTrace($"Entering ProcessPostCopyOperationsAsync for report type: {reportType}");
            var stopwatch = Stopwatch.StartNew();

            // Retrieve additional sheet and pivot table names from configuration.
            string powerBiSheetName = _configuration.GetValue<string>("OperationalParameters:ExcelSheetNames:PowerBiDataSheet", "powerBI")!;
            string monthlyOrderPivotSheetName = _configuration.GetValue<string>("OperationalParameters:ExcelSheetNames:MonthlyOrderPivotSheet", "OrderPivot")!;
            string monthlyEstimatePivotSheetName = _configuration.GetValue<string>("OperationalParameters:ExcelSheetNames:MonthlyEstimatePivotSheet", "Estimate Success PivotTable")!;
            string monthlyOrderPivotName = _configuration.GetValue<string>("OperationalParameters:PivotTableNames:MonthlyOrderPivot", "PivotTable1")!;
            string monthlyEstimatePivotName = _configuration.GetValue<string>("OperationalParameters:PivotTableNames:MonthlyEstimatePivot", "PivotTable3")!;

            // 1. Extract unique customers from the 'DATA' sheet and populate them into the 'Analysis' sheet.
            _statusManager.Post("Extracting unique customers to Analysis sheet...", MessageType.InProgress);
            await ExtractUniqueCustomersAsync(sourceDataWorksheet, targetAnalysisWorksheet, dataColumnMap, analysisColumnMap, reportType, originalSourceFilePath, reportDate, cancellationToken);
            cancellationToken.ThrowIfCancellationRequested();

            // 2. Trigger the calculation of all formulas in the workbook.
            _statusManager.Post("Calculating formulas in Analysis sheet...", MessageType.InProgress);
            await Task.Run(() => CalculateSheet(package, targetAnalysisWorksheet.Name), cancellationToken);
            cancellationToken.ThrowIfCancellationRequested();

            // 3. For specific report types, filter the 'Analysis' sheet to remove irrelevant rows.
            if (reportType == ReportType.Daily5Day1k)
            {
                _statusManager.Post("Filtering Analysis sheet for zero estimates...", MessageType.InProgress);
                await FilterAnalysisSheetForZeroEstimatesAsync(targetAnalysisWorksheet, analysisColumnMap, cancellationToken);
                cancellationToken.ThrowIfCancellationRequested();
            }

            // 4. Clean up any unused template rows below the last populated customer in the 'Analysis' sheet.
            _statusManager.Post("Cleaning unused rows...", MessageType.InProgress);
            await Task.Run(() => ClearContentBelowLastCustomer(targetAnalysisWorksheet, analysisColumnMap), cancellationToken);
            cancellationToken.ThrowIfCancellationRequested();

            // 5. For reports that use templates with pivot tables, set them to refresh when the file is opened.
            if (reportType is ReportType.Monthly or ReportType.Quarterly or ReportType.Annual or ReportType.Custom)
            {
                _statusManager.Post("Setting pivot tables to refresh...", MessageType.InProgress);
                await Task.Run(() => RefreshPivotTable(package, monthlyOrderPivotSheetName, monthlyOrderPivotName), cancellationToken);
                await Task.Run(() => RefreshPivotTable(package, monthlyEstimatePivotSheetName, monthlyEstimatePivotName), cancellationToken);
                cancellationToken.ThrowIfCancellationRequested();
            }

            // 6. For Weekly reports, append the processed data to the central Power BI source file.
            if (reportType == ReportType.Weekly)
            {
                _statusManager.Post("Appending data to Power BI source file...", MessageType.InProgress);
                await CopyAnalysisDataToPowerBIReportAsync(package, targetAnalysisWorksheet.Name, powerBiSheetName, reportType, originalSourceFilePath, reportDate, cancellationToken);
                cancellationToken.ThrowIfCancellationRequested();
            }

            // Log the completion of the post-copy process.
            stopwatch.Stop();
            Logger.LogDebug($"Exiting ProcessPostCopyOperationsAsync. Duration: {stopwatch.ElapsedMilliseconds}ms");
        }

