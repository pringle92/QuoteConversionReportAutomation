        /// <summary>
        /// Scans the header row of a worksheet to build a dictionary that maps column names to their 1-based index.
        /// This makes the application resilient to changes in column order within the template files.
        /// </summary>
        /// <param name="worksheet">The worksheet to scan.</param>
        /// <param name="headerRow">The row number where the headers are located.</param>
        /// <param name="requiredColumns">An enumerable of column names that must be present in the header.</param>
        /// <returns>A dictionary mapping each column name to its integer index.</returns>
        /// <exception cref="InvalidOperationException">
        /// Thrown if the header row does not exist or if a required column is not found.
        /// </exception>
        private Dictionary<string, int> MapColumnIndices(ExcelWorksheet worksheet, int headerRow, IEnumerable<string> requiredColumns)
        {
            // Initialise a case-insensitive dictionary to store the mapping.
            var columnMap = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);

            // Check if the worksheet dimensions are valid and the header row exists.
            if (worksheet.Dimension == null || worksheet.Dimension.End.Row < headerRow)
            {
                throw new InvalidOperationException($"Header row {headerRow} does not exist in worksheet '{worksheet.Name}'. The sheet is empty or malformed.");
            }

            // Iterate through each column in the header row.
            for (int col = 1; col <= worksheet.Dimension.End.Column; col++)
            {
                // Get the trimmed header text from the cell.
                var cellValue = worksheet.Cells[headerRow, col].Value?.ToString()?.Trim();

                // If the header text is not empty and not already in the map, add it.
                if (!string.IsNullOrEmpty(cellValue) && !columnMap.ContainsKey(cellValue))
                {
                    columnMap[cellValue] = col;
                }
            }

            // Verify that all required columns were found in the map.
            foreach (var requiredColumn in requiredColumns)
            {
                if (!columnMap.ContainsKey(requiredColumn))
                {
                    // If a required column is missing, throw a descriptive exception.
                    throw new InvalidOperationException($"Required column '{requiredColumn}' not found in the header of worksheet '{worksheet.Name}'. Please check the template file.");
                }
            }

            // Return the completed map.
            return columnMap;
        }

        /// <summary>
        /// Ensures the destination 'DATA' sheet exists in the workbook. If it exists, it clears any old data.
        /// If it does not exist, it creates the sheet and copies the header row from the source worksheet.
        /// </summary>
        /// <param name="package">The Excel package to modify.</param>
        /// <param name="sheetName">The name of the destination sheet (e.g., "DATA").</param>
        /// <param name="sourceWorksheet">The source worksheet to copy headers from if the destination sheet needs to be created.</param>
        /// <returns>The prepared destination worksheet.</returns>
        private ExcelWorksheet GetOrCreateDestinationWorksheet(ExcelPackage package, string sheetName, ExcelWorksheet sourceWorksheet)
        {
            // Attempt to get the worksheet by name.
            ExcelWorksheet? worksheet = package.Workbook.Worksheets[sheetName];

            // If the sheet does not exist...
            if (worksheet == null)
            {
                // ...create it.
                worksheet = package.Workbook.Worksheets.Add(sheetName);
                Logger.LogInfo($"Created destination sheet '{sheetName}'.");

                // Copy the header row from the source worksheet.
                CopyHeaders(sourceWorksheet, worksheet);
            }
